const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const {start, replacement, patchQueue} = require('./queue-compat.cjs');
const extension = process.argv[2];
assert(extension, 'Pass the installed openai.chatgpt extension directory');
const source = fs.readFileSync(path.join(extension, 'webview/assets/src-622b307a9baf.js'), 'utf8');
const begin = source.indexOf(start);
const end = source.indexOf(',findByClientMessageId:', begin);
assert(begin >= 0 && end > begin);
const predicate = source.slice(begin, end);
const fixture = `({${predicate},findByClientMessageId:null})`;
const patched = patchQueue(fixture);
assert(patched.includes(replacement));
assert.equal(patchQueue(patched), patched);
let role = 'follower';
const context = {e: {getStreamRole: () => ({role})}, t: false, g: () => true, me: () => true};
const original = vm.runInNewContext(fixture, context);
const fixed = vm.runInNewContext(patched, context);
const message = {context: {turnTrigger: 'composer'}};
assert.equal(original.canEnqueue('thread', message), true, 'Original incorrectly chooses direct enqueue');
assert.equal(fixed.canEnqueue('thread', message), false, 'Follower must use owner forwarding');
role = 'leader';
assert.equal(fixed.canEnqueue('thread', message), true);
context.t = true;
assert.equal(fixed.canEnqueue('thread', message), true);
message.context.requiresLocalPreparation = true;
assert.equal(fixed.canEnqueue('thread', message), false);
console.log('PASS: real Codex queue predicate routes followers to owner and preserves admission checks');
